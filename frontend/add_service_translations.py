content = file.read_text(encoding="utf-8")

if "service_cybersecurity_title" in content:
    raise SystemExit("ERROR: Service translations already exist. Restore backup first.")

# Find every placeholder_name from bottom to top.
# This prevents line positions from changing while we insert.
positions = []

search_from = 0

while True:
    pos = content.find('        "placeholder_name":', search_from)

    if pos == -1:
        break

    positions.append(pos)
    search_from = pos + 1

if len(positions) != 10:
    raise SystemExit(
        f"ERROR: Expected 10 placeholder_name entries, found {len(positions)}"
    )

languages = [
    "en", "fr", "es", "pt", "sw",
    "de", "ar", "zh", "hi", "ja"
]

# Insert from bottom to top.
for lang, pos in reversed(list(zip(languages, positions))):

    lines = []

    for key, value in translations[lang]:
        safe_value = value.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'        "{key}": "{safe_value}",')

    insertion = "\n".join(lines) + "\n"

    content = content[:pos] + insertion + content[pos:]

file.write_text(content, encoding="utf-8")

print("SUCCESS: All 100 service translation keys added.")
